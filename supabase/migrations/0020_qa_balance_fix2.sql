-- ============================================================
--  0020: QA 잔액 재보정 — 짝 잃은 투자 기록을 일반 삭제로 지웠을 때
--
--  0019 로 내가 정리하기 전에, 사용자가 화면에서 먼저 세 건(인출·자기
--  투자·50,000원 투자)을 순서대로 다 지웠다. 앞의 두 건은 문제없었지만
--  마지막 "투자 지갑으로 이동 -50,000"은 짝(예전 버그로 이미 사라진
--  "+50,000 용돈 지급")이 없는 고아 기록이라, 일반 delete_transaction
--  이 "이 줄이 balance 를 50,000원 줄였었다"고 오해해 삭제 시 balance
--  에 50,000원을 잘못 더했다(1,000원이어야 할 게 51,000원이 됨 —
--  실제 남은 거래내역을 전부 더하면 1,000원이 나온다).
-- ============================================================

do $$ begin
  perform set_config('app.bal','ok',true);
  update members set balance = balance - 50000
    where id = '60e6368d-5d68-486c-8336-5a5a607e1094' and balance = 51000;
end $$;
